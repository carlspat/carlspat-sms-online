const {test}=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const SQLite=require('../sqlite.cjs')
const {openDatabase}=require('../../electron/storage.cjs')
const {createServices}=require('../../electron/services.cjs')
test('Principal can supervise academics while finance, accounts, settings and backups stay blocked',()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'principal-test-'))
  const db=openDatabase(path.join(root,'school.sqlite'),SQLite)
  try {
    const api=createServices(db,{getPath:()=>root})
    const admin=api.auth.createFirstAdmin({username:'owner',password:'TestPassword123'})
    api.users.create(admin.token,{username:'principal',password:'PrincipalPassword123',role:'Principal'})
    const {token,user}=api.auth.login({username:'principal',password:'PrincipalPassword123'})
    assert.deepEqual(user.roles,['Principal'])
    for(const permission of ['students.read','students.manage','parents.read','staff.read','attendance.read','attendance.manage','academics.read','academics.manage','academics.approve'])assert.ok(user.permissions.includes(permission),permission)
    for(const permission of ['finance.read','finance.manage','users.manage','school.manage','backups.manage','reports.read'])assert.ok(!user.permissions.includes(permission),permission)
    assert.deepEqual(api.users.parents(token),[])
    assert.deepEqual(api.classes.teachers(token),[])
    assert.deepEqual(api.students.list(token),[])
    assert.deepEqual(api.attendance.list(token),[])
    assert.deepEqual(api.academics.results(token),[])
    const session=api.school.createSession(admin.token,{name:'2026/2027',active:true})
    const term=api.school.createTerm(admin.token,{name:'First Term',sessionId:session.id,active:true})
    assert.equal(api.academics.approveResults(token,{sessionId:session.id,termId:term.id}).approved,0)
    for(const action of [()=>api.finance.categories(token),()=>api.finance.payments(token),()=>api.users.list(token),()=>api.school.update(token,{name:'Forbidden'}),()=>api.school.createSession(token,{name:'2027/2028'}),()=>api.reports.data(token,'payments')])assert.throws(action,/permission/)
    db.exec("INSERT INTO classes(id,name,level) VALUES(1,'JSS 1','Junior Secondary'); INSERT INTO class_arms(id,class_id,name) VALUES(1,1,'A')")
    db.prepare("INSERT INTO students(id,admission_number,first_name,surname,gender,admission_date,session_id,class_arm_id) VALUES('pupil','OSC-1','Test','Pupil','Female','2026-09-01',?,1)").run(session.id)
    db.prepare("INSERT INTO report_cards(id,student_id,session_id,term_id,status) VALUES('card','pupil',?,?,'Draft')").run(session.id,term.id)
    api.academics.saveReportComments(token,{id:'card',classTeacherComment:'Good progress',headTeacherComment:'Keep improving'})
    api.academics.publishReport(token,'card')
    assert.equal(api.academics.getReportCard(token,'pupil',session.id,term.id).head_teacher_comment,'Keep improving')
    api.academics.saveReportComments(token,{id:'card',headTeacherComment:'Excellent effort'})
    assert.equal(api.academics.getReportCard(token,'pupil',session.id,term.id).head_teacher_comment,'Excellent effort')
    const profile=api.students.profile(token,'pupil')
    assert.ok(!Object.hasOwn(profile,'finance'))
  } finally {db.close();fs.rmSync(root,{recursive:true,force:true})}
})
