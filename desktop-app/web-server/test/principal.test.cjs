const {test}=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const SQLite=require('../sqlite.cjs')
const {openDatabase}=require('../../electron/storage.cjs')
const {createServices}=require('../../electron/services.cjs')
test('Principal can approve stakeholders and manage finance and ordinary accounts while settings and Super Admin accounts stay protected',()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'principal-test-'))
  const db=openDatabase(path.join(root,'school.sqlite'),SQLite)
  try {
    const api=createServices(db,{getPath:()=>root})
    const admin=api.auth.createFirstAdmin({username:'owner',password:'TestPassword123'})
    api.users.create(admin.token,{username:'principal',password:'PrincipalPassword123',role:'Principal'})
    const {token,user}=api.auth.login({username:'principal',password:'PrincipalPassword123'})
    assert.deepEqual(user.roles,['Principal'])
    for(const permission of ['students.read','students.manage','parents.read','staff.read','attendance.read','attendance.manage','academics.read','academics.manage','academics.approve','stakeholders.read','stakeholders.manage','users.manage','finance.read','finance.manage','reports.read'])assert.ok(user.permissions.includes(permission),permission)
    for(const permission of ['school.manage','backups.manage'])assert.ok(!user.permissions.includes(permission),permission)
    assert.deepEqual(api.users.parents(token),[])
    assert.deepEqual(api.classes.teachers(token),[])
    assert.deepEqual(api.students.list(token),[])
    assert.deepEqual(api.attendance.list(token),[])
    assert.deepEqual(api.academics.results(token),[])
    const session=api.school.createSession(admin.token,{name:'2026/2027',active:true})
    const term=api.school.createTerm(admin.token,{name:'First Term',sessionId:session.id,active:true})
    assert.equal(api.academics.approveResults(token,{sessionId:session.id,termId:term.id}).approved,0)
    assert.deepEqual(api.finance.categories(token),[])
    assert.deepEqual(api.finance.payments(token),[])
    assert.equal(api.users.list(token).length,2)
    const teacher=api.users.create(token,{username:'teacher',password:'TeacherPassword123',role:'Teacher'})
    api.users.update(token,teacher.id,{username:'teacher-edited',email:'teacher@example.test'})
    api.users.resetPassword(token,teacher.id,'NewTeacherPassword123')
    assert.ok(api.auth.login({username:'teacher-edited',password:'NewTeacherPassword123'}).token)
    api.users.deactivate(token,teacher.id)
    assert.throws(()=>api.users.create(token,{username:'admin2',password:'AdminPassword123',role:'Super Admin'}),/Only a Super Admin/)
    for(const action of [()=>api.users.update(token,admin.user.id,{username:'changed'}),()=>api.users.resetPassword(token,admin.user.id,'NewAdminPassword123'),()=>api.users.deactivate(token,admin.user.id)])assert.throws(action,/Only a Super Admin/)
    const application=api.stakeholders.selfRegister({username:'partner',password:'PartnerPassword123',name:'Partner School',email:'partner@example.test',phone:'08000000000',representative:'School Head'})
    const stakeholder=db.prepare('SELECT id FROM stakeholder_schools WHERE user_id=?').get(application.user.id)
    api.stakeholders.review(token,stakeholder.id,'Approved')
    assert.equal(db.prepare('SELECT status FROM stakeholder_schools WHERE id=?').get(stakeholder.id).status,'Approved')
    for(const action of [()=>api.school.update(token,{name:'Forbidden'}),()=>api.school.createSession(token,{name:'2027/2028'})])assert.throws(action,/permission/)
    db.exec("INSERT INTO classes(id,name,level) VALUES(1,'JSS 1','Junior Secondary'); INSERT INTO class_arms(id,class_id,name) VALUES(1,1,'A')")
    db.prepare("INSERT INTO students(id,admission_number,first_name,surname,gender,admission_date,session_id,class_arm_id) VALUES('pupil','OSC-1','Test','Pupil','Female','2026-09-01',?,1)").run(session.id)
    db.prepare("INSERT INTO report_cards(id,student_id,session_id,term_id,status) VALUES('card','pupil',?,?,'Draft')").run(session.id,term.id)
    api.academics.saveReportComments(token,{id:'card',classTeacherComment:'Good progress',headTeacherComment:'Keep improving'})
    api.academics.publishReport(token,'card')
    assert.equal(api.academics.getReportCard(token,'pupil',session.id,term.id).head_teacher_comment,'Keep improving')
    api.academics.saveReportComments(token,{id:'card',headTeacherComment:'Excellent effort'})
    assert.equal(api.academics.getReportCard(token,'pupil',session.id,term.id).head_teacher_comment,'Excellent effort')
    const profile=api.students.profile(token,'pupil')
    assert.ok(Object.hasOwn(profile,'fees'))
    const category=api.finance.createCategory(token,{name:'Tuition'})
    api.finance.assignFee(token,{categoryId:category.id,sessionId:session.id,termId:term.id,studentId:'pupil',amount:1000})
    api.finance.recordPayment(token,{studentId:'pupil',sessionId:session.id,termId:term.id,amount:400,method:'Cash'})
    assert.equal(api.finance.payments(token)[0].amount,400)
    assert.equal(api.students.profile(token,'pupil').fees.outstanding,600)
  } finally {db.close();fs.rmSync(root,{recursive:true,force:true})}
})
