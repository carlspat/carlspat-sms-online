const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { openDatabase } = require('../../electron/storage.cjs')
const { createServices } = require('../../electron/services.cjs')
const SQLite = require('../sqlite.cjs')
test('desktop services create admin, persist sessions, edit academic session, and reject invalid authentication', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sms-service-test-'))
  const db = openDatabase(path.join(root, 'school.sqlite'), SQLite)
  try {
    const services = createServices(db, {getPath:()=>root})
    assert.equal(services.auth.needsSetup(), true)
    const admin = services.auth.createFirstAdmin({username:'admin-test',email:'admin@example.test',password:'LongTestPassword123'})
    assert.ok(services.auth.me(admin.token).permissions.includes('school.manage'))
    assert.throws(()=>services.auth.createFirstAdmin({}), /already/)
    assert.throws(()=>services.auth.me('invalid-session-token-12345'), /expired/)
    const created = services.school.createSession(admin.token,{name:'2026/2027',active:true})
    services.school.updateSession(admin.token,created.id,{name:'2027/2028',active:true})
    assert.equal(services.school.academicData(admin.token).sessions[0].name,'2027/2028')
    services.classes.create(admin.token,{name:'Primary One',level:'Primary',arms:[{name:'A'}]})
    const arm = db.prepare('SELECT id FROM class_arms LIMIT 1').get().id
    const pupil = services.students.create(admin.token,{firstName:'Ada',surname:'One',gender:'Female',sessionId:created.id,classArmId:arm,parent:{firstName:'Parent',surname:'One',phone:'08000000001'}})
    services.students.create(admin.token,{firstName:'Bola',surname:'Two',gender:'Male',sessionId:created.id,classArmId:arm,parent:{firstName:'Parent',surname:'Two',phone:'08000000002'}})
    const parentId = db.prepare('SELECT parent_id FROM student_parents WHERE student_id=?').get(pupil.id).parent_id
    services.users.create(admin.token,{username:'parent-one',role:'Parent',parentId,password:'ParentPassword123'})
    const parent = services.auth.login({username:'parent-one',password:'ParentPassword123'})
    assert.deepEqual(services.students.list(parent.token).map(row=>row.id),[pupil.id])
    const other = services.students.list(admin.token).find(row=>row.id!==pupil.id)
    assert.throws(()=>services.students.profile(parent.token,other.id), /not linked/)
    assert.throws(()=>services.school.update(parent.token,{name:'Invalid'}), /permission/)
    assert.throws(()=>services.users.list(parent.token), /permission/)
    const photo = path.join(root,'passport.png'); fs.writeFileSync(photo,'photo fixture')
    db.prepare('UPDATE students SET photograph_path=? WHERE id=?').run(photo,pupil.id)
    const {portableBackup} = require('../../electron/portable-backup.cjs')
    const archive = portableBackup(db,SQLite)
    const state = JSON.parse(require('node:zlib').gunzipSync(archive.bytes))
    const migrated = new SQLite(Buffer.from(state.database,'base64'))
    try {
      assert.equal(migrated.prepare('SELECT COUNT(*) n FROM sessions').get().n,0)
      assert.equal(Object.keys(state.files).length,1)
      assert.ok(migrated.prepare('SELECT photograph_path p FROM students WHERE id=?').get(pupil.id).p.startsWith('/school-export/assets/'))
      assert.equal(db.prepare('SELECT photograph_path p FROM students WHERE id=?').get(pupil.id).p,photo)
      assert.ok(services.auth.me(admin.token))
    } finally {migrated.close()}
    services.auth.logout(admin.token)
    assert.throws(()=>services.auth.me(admin.token), /expired/)
  } finally { db.close(); fs.rmSync(root,{recursive:true,force:true}) }
})
